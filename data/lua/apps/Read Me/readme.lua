About this guide.

The Guide tab is the general manual. Its pages are written for the device you are holding - a touch-only device gets touch instructions, a device with a keyboard gets keyboard ones - so nothing here describes hardware you do not have.

The Apps tab has one page per installed app. A page ships inside the app it belongs to, so installing an app from the App Library adds its help here too, and the list always matches what is installed.

For tinkerers: Guide pages are Lua files in lua/help on internal storage or the SD card, and an app ships its own page as a readme.lua inside its folder.]] }
